import { test, expect } from '@playwright/test'
import { addTransaction, blockExternalNetwork, initializeWorkspace } from './support/flows'
import { collectRuntimeErrors, expectNoRuntimeErrors } from './support/quality'

test.setTimeout(60_000)

test.beforeEach(async ({ page }) => {
  collectRuntimeErrors(page)
  await blockExternalNetwork(page)
})
test.afterEach(async ({ page }, testInfo) => expectNoRuntimeErrors(page, testInfo))

test('records the authoritative ledger, budget, dashboard drill-down, activity, and exports', async ({ page }) => {
  await initializeWorkspace(page)
  await addTransaction(page, 'income', '2500', 'Salary')
  await addTransaction(page, 'expense', '125.50', 'Food')

  await page.getByRole('link', { name: 'Accounts' }).click()
  await page.getByRole('button', { name: 'Add account' }).click()
  const accountDialog = page.getByRole('dialog', { name: 'Add an account' })
  await accountDialog.getByLabel('Account name').fill('Savings')
  await accountDialog.getByRole('button', { name: 'Create account' }).click()
  await expect(accountDialog).toBeHidden()

  await page.getByRole('button', { name: 'Quick add transaction' }).click()
  const transfer = page.getByRole('dialog', { name: 'Add transaction' })
  await transfer.getByRole('radio', { name: 'Transfer' }).check()
  await transfer.getByLabel('Amount').fill('100')
  await transfer.getByLabel('From account').selectOption({ label: 'Everyday · USD' })
  await transfer.getByLabel('To account').selectOption({ label: 'Savings · USD' })
  await transfer.getByRole('button', { name: 'Add transaction' }).click()
  await expect(transfer).toBeHidden()

  await page.getByRole('link', { name: 'Transactions' }).click()
  const table = page.getByRole('table')
  await expect(table.getByRole('row').filter({ hasText: 'Salary' })).toContainText('SalaryIncomeEveryday')
  await expect(table.getByRole('row').filter({ hasText: 'Salary' })).toContainText('Completed+$2,500.00')
  await expect(table.getByRole('row').filter({ hasText: 'Food' })).toContainText('FoodExpenseEveryday')
  await expect(table.getByRole('row').filter({ hasText: 'Food' })).toContainText('Completed−$125.50')
  await expect(table.getByRole('row').filter({ hasText: 'Transfer' })).toContainText('TransferEveryday → Savings')
  await expect(table.getByRole('row').filter({ hasText: 'Transfer' })).toContainText('Completed$100.00')
  await page.getByRole('link', { name: 'Accounts' }).click()
  await expect(page.locator('.account-card').filter({ hasText: 'Everyday' })).toContainText('$3,274.50')
  await expect(page.locator('.account-card').filter({ hasText: 'Savings' })).toContainText('$100.00')
  await page.getByRole('link', { name: 'Transactions' }).click()
  await page.getByRole('button', { name: 'Export CSV' }).click()
  await expect(page.getByRole('status')).toContainText('exported')

  await page.getByRole('link', { name: 'Budgets' }).click()
  await page.getByRole('button', { name: 'Create budget' }).first().click()
  const budget = page.getByRole('dialog', { name: 'Create budget' })
  await budget.getByLabel('Category').selectOption({ label: 'Food' })
  await budget.getByLabel('Amount').fill('500')
  await budget.getByRole('button', { name: 'Save budget' }).click()
  await expect(budget).toBeHidden()
  const totals = page.getByLabel('Budget totals')
  await expect(totals).toContainText('Planned$500.00')
  await expect(totals).toContainText('Spent$125.50')
  await expect(totals).toContainText('Remaining$374.50')
  const foodBudget = page.locator('.budget-card').filter({ hasText: 'Food' })
  await expect(foodBudget).toContainText('$125.50of $500.00')
  await expect(foodBudget).toContainText('On track')
  await expect(foodBudget).toContainText('25% used · $374.50 left')

  await page.getByRole('link', { name: 'Dashboard' }).click()
  const overview = page.getByLabel('Financial overview')
  await expect(overview.locator('.kpi-card').filter({ hasText: 'Net worth' })).toContainText('$3,374.50')
  await expect(overview.locator('.kpi-card').filter({ hasText: 'Income' })).toContainText('$2,500.00')
  await expect(overview.locator('.kpi-card').filter({ hasText: 'Expenses' })).toContainText('$125.50')
  await expect(overview.locator('.kpi-card').filter({ hasText: 'Net flow' })).toContainText('$2,374.50')
  const spending = page.locator('.dashboard-panel').filter({ hasText: 'Spending mix' })
  const foodBreakdown = spending.getByRole('row').filter({ hasText: 'Food' })
  await expect(foodBreakdown.getByRole('cell').nth(1)).toHaveText('$125.50')
  await expect(foodBreakdown.getByRole('cell').nth(2)).toHaveText('100%')
  const categoryLink = page.getByRole('link', { name: /Food.*view expense transactions/i })
  await expect(categoryLink).toBeVisible()
  await categoryLink.click()
  await expect(page.locator('select[aria-label="Category"]')).toHaveValue('food')

  await page.getByRole('link', { name: 'Activity' }).click()
  await expect(page.getByRole('heading', { name: 'Activity' })).toBeVisible()
  await expect(page.getByText(/transaction created/i).first()).toBeVisible()

  await page.getByRole('link', { name: 'Settings' }).click()
  await page.getByRole('button', { name: 'Export JSON' }).click()
  await expect(page.getByRole('status')).toContainText('JSON backup exported')
  await page.getByRole('button', { name: 'Export all CSV' }).click()
  await expect(page.getByRole('status')).toContainText('CSV exported')
})

test('recovers from backup-folder denial with an alternative folder and keeps exact finance state', async ({ page }) => {
  await initializeWorkspace(page)
  await addTransaction(page, 'expense', '12.34', 'Food')
  await page.evaluate(() => localStorage.setItem('miroratrack.e2e.folder-mode', 'deny'))
  await page.getByRole('link', { name: 'Settings' }).click()
  await page.getByRole('button', { name: 'Choose folder' }).click()
  await expect(page.getByRole('status')).toContainText(/permission|denied/i)
  await page.getByRole('button', { name: 'Choose folder' }).click()
  await expect(page.getByRole('status')).toContainText('Backup folder updated.')
  await expect(page.locator('.configured-path')).toHaveText('D:\\MiroraTrack\\Backups')
  await page.getByRole('button', { name: 'Retry now' }).click()
  await expect(page.getByRole('status')).toContainText('Backup completed successfully.')
  await expect(page.getByText('Automatic backups are healthy')).toBeVisible()
  await page.getByRole('link', { name: 'Accounts' }).click()
  const account = page.locator('.account-card').filter({ hasText: 'Everyday' })
  await expect(account).toContainText('$987.66')
})
